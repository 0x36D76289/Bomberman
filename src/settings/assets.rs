use anyhow::{Result, anyhow};

macro_rules! embed {
    ($($path:literal),* $(,)?) => {
        &[$((
            $path,
            include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/assets/", $path)) as &[u8],
        )),*]
    };
}

